// Generates the committed pure-data bounds artifact from the exact merged
// geometry used by the runtime. Run after model/recipe changes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as THREE from 'three';
import { VISUAL_ARCHETYPES } from '../src/content/archetypes.js';
import { visualGeometryFingerprint } from '../src/content/propkit.js';
import { createLandmark } from '../src/content/landmarks.js';
import { METROS } from '../src/data/metros.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'src', 'content', 'physical-bounds.generated.js');
const records = {};
const landmarkRecords = {};

for (const descriptor of Object.values(VISUAL_ARCHETYPES).sort((a, b) => a.id.localeCompare(b.id))) {
  const measured = visualGeometryFingerprint(descriptor.id, descriptor.gameplayKind, THREE).bounds;
  if (!Array.isArray(measured) || measured.length !== 6 || measured.some((n) => !Number.isFinite(n))) {
    throw new Error(`Invalid merged bounds: ${descriptor.id}`);
  }
  records[descriptor.id] = {
    minX: measured[0], minY: measured[1], minZ: measured[2],
    maxX: measured[3], maxY: measured[4], maxZ: measured[5],
  };
}

for (const metro of METROS) {
  const object = createLandmark(metro.landmarkType, THREE, metro.accent);
  object.updateMatrixWorld(true);
  const box = new THREE.Box3().setFromObject(object);
  const sphere = new THREE.Sphere();
  box.getBoundingSphere(sphere);
  landmarkRecords[metro.landmarkType] = {
    minX: box.min.x, minY: box.min.y, minZ: box.min.z,
    maxX: box.max.x, maxY: box.max.y, maxZ: box.max.z,
    boundingRadius: sphere.radius,
  };
}

const source = `// Generated by scripts/generate-physical-bounds.js. Do not hand-edit.\n`
  + `export const GENERATED_PHYSICAL_BOUNDS = Object.freeze(${JSON.stringify(records, null, 2)});\n`
  + `export const GENERATED_LANDMARK_BOUNDS = Object.freeze(${JSON.stringify(landmarkRecords, null, 2)});\n`;
fs.writeFileSync(output, source, 'utf8');
console.log(`Wrote ${Object.keys(records).length} prop and ${Object.keys(landmarkRecords).length} landmark bounds to ${path.relative(root, output)}`);
