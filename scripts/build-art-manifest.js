/* Builds assets/art-manifest.json — the contract the game-wiring code reads.

   Hard rule: an entry only appears if its PNG actually exists on disk AND is a
   valid non-empty PNG. A missing/corrupt file is simply absent from the
   manifest, so a consumer can treat "listed" as "safe to load" and fall back to
   the generic textures for anything absent.

   Run: node scripts/build-art-manifest.js
*/
const fs = require('fs');
const path = require('path');
const { ROOT, isValidPng } = require('./pixellab');
const { buildJobs, TEXTURE_SLOTS } = require('./art-spec');

function buildManifest() {
  const jobs = buildJobs();

  const metros = {};
  const icons = { upgrades: {}, achievements: {}, collection: {} };
  const counts = { textures: 0, icons: 0, missing: [] };

  for (const job of jobs) {
    const abs = path.join(ROOT, job.relPath);
    if (!isValidPng(abs)) { counts.missing.push(job.relPath); continue; }
    const rel = job.relPath.replace(/\\/g, '/');
    if (job.category === 'texture') {
      if (!metros[job.metro]) metros[job.metro] = {};
      metros[job.metro][job.slot] = rel;
      counts.textures++;
    } else {
      icons[job.iconCategory][job.id] = rel;
      counts.icons++;
    }
  }

  // Drop empty icon categories rather than shipping empty objects.
  for (const cat of Object.keys(icons)) {
    if (Object.keys(icons[cat]).length === 0) delete icons[cat];
  }

  const manifest = {
    $comment:
      'Generated by scripts/build-art-manifest.js. Every path listed here points at a ' +
      'verified non-empty PNG relative to the repo root. Slots absent from a metro have ' +
      'no generated art yet — fall back to the generic textures in assets/textures/.',
    generatedAt: new Date().toISOString(),
    textureSlots: TEXTURE_SLOTS,
    metros,
    icons,
  };

  return { manifest, counts };
}

function writeManifest() {
  const { manifest, counts } = buildManifest();
  const dest = path.join(ROOT, 'assets', 'art-manifest.json');
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, JSON.stringify(manifest, null, 2) + '\n');
  return { dest, counts, manifest };
}

if (require.main === module) {
  const { dest, counts } = writeManifest();
  console.log(`Wrote ${dest}`);
  console.log(`  textures listed: ${counts.textures}`);
  console.log(`  icons listed:    ${counts.icons}`);
  console.log(`  not yet on disk: ${counts.missing.length}`);
}

module.exports = { buildManifest, writeManifest };
